import type { Maker } from './makers'

/** Who owns a brand name, as far as a published source says. */
export interface BrandOwner {
  owner: string | null
  /** The founder, or the person known as the face of it. */
  people: string | null
  /** True when the owner also owns the factory that rolls it. Null when no source says. */
  ownsFactory: boolean | null
  /** Who sells it in the US, when that is a different company. */
  distributor: string | null
  note: string | null
  sources: string[]
}

/** A researched line that may not be on his cigar list, and the factory that rolls it. */
export interface Extra {
  brand: string
  lines: string
  /** Factory text, matched the same way as the cigar list's. */
  factory: string
  since: number | null
  until: number | null
  note: string | null
  sources: string[]
}

/** A brand that left one factory for another. */
export interface Move {
  brand: string
  from: string
  to: string
  year: number | null
  note: string | null
  sources: string[]
}

export interface Story {
  key: string
  /** "video" for the ones the Momento Cigars video tells, "more" for the rest. */
  from: 'video' | 'more'
  title: string
  body: string[]
  /** Brands to jump to, spelled as the cigar list spells them. */
  brands: string[]
  sources: string[]
}

